text = open("recommendations/mountain_data.py", encoding="utf-8").read()

def replace_desc(name, new_desc, src):
    # 이름이 정확히 매칭되는 블록에서 description만 교체
    pattern = rf'("id":\s*"m-{re.escape(name)}".*?"description":\s*)"((?:[^"\\]|\\.)*?)"'
    replacement = rf'\1"{new_desc}"'
    result, count = re.subn(pattern, replacement, src, flags=re.DOTALL)
    if count == 0:
        # id 방식 대신 name으로 매칭
        pattern2 = rf'("name":\s*"{re.escape(name)}".*?"description":\s*)"((?:[^"\\]|\\.)*?)"'
        result, count = re.subn(pattern2, replacement, src, flags=re.DOTALL)
    return result, count

total = 0
for name, desc in DESCRIPTIONS.items():
    text, n = replace_desc(name, desc, text)
    if n:
        total += n
        print(f"  OK  : {name}")
    else:
        print(f"  MISS: {name}")

open("recommendations/mountain_data.py", "w", encoding="utf-8").write(text)
print(f"\n완료: {total}개 설명 교체")
